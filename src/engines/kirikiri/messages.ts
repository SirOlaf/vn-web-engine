export type KirikiriMessages = Readonly<Record<KirikiriMessageName, string>>;

const LANG_ENGLISH = 0x09;

/** The built-in English texts. */
export const ENGLISH_MESSAGES: KirikiriMessages = Object.freeze(
  Object.fromEntries(KIRIKIRI_MESSAGE_NAMES.map((name, i) => [name, ENGLISH[i]!])),
) as KirikiriMessages;

/** RT_STRING tables of a PE image: language → string id → text. */
export function readStringTables(image: Uint8Array): Map<number, Map<number, string>> {
  const byLanguage = new Map<number, Map<number, string>>();
  for (const block of parsePeResources(image, [6])) {
    if (typeof block.id !== 'number') continue;
    let table = byLanguage.get(block.language);
    if (!table) byLanguage.set(block.language, (table = new Map()));
    const b = block.bytes;
    let o = 0;
    for (let i = 0; i < 16 && o + 2 <= b.length; i++) {
      const n = b[o]! | (b[o + 1]! << 8);
      o += 2;
      if (n) table.set((block.id - 1) * 16 + i, utf16(b.subarray(o, o + n * 2)));
      o += n * 2;
    }
  }
  return byLanguage;
}

/**
 * Picks the string-table language the way resource loading does for a UI language: the
 * exact LANGID, then the same primary language, then English, then the first available.
 */
export function pickLanguage(available: Iterable<number>, uiLanguage: number): number | undefined {
  const langs = [...available];
  return (
    langs.find((l) => l === uiLanguage) ??
    langs.find((l) => (l & 0x3ff) === (uiLanguage & 0x3ff)) ??
    langs.find((l) => (l & 0x3ff) === LANG_ENGLISH) ??
    langs[0]
  );
}

/**
 * Reads every core message from the executable's string tables for a UI language. Strings the
 * executable does not contain keep the built-in English text.
 */
export function readKirikiriMessages(executable: Uint8Array, uiLanguage: number): KirikiriMessages {
  const tables = readStringTables(executable);
  const language = pickLanguage(tables.keys(), uiLanguage);
  const table = language === undefined ? undefined : tables.get(language);
  if (!table) return ENGLISH_MESSAGES;
  const out: Record<string, string> = {};
  KIRIKIRI_MESSAGE_NAMES.forEach((name, i) => {
    out[name] = table.get(MESSAGE_BASE + i) ?? ENGLISH[i]!;
  });
  return Object.freeze(out) as KirikiriMessages;
}

/** `ttstr::Replace` of `%1`, `%2`, … in order, every occurrence, as the core builds messages. */
export function formatMessage(text: string, ...args: readonly string[]): string {
  let out = text;
  args.forEach((arg, i) => {
    out = out.split(`%${i + 1}`).join(arg);
  });
  return out;
}

function utf16(bytes: Uint8Array): string {
  let s = '';
  for (let i = 0; i + 1 < bytes.length; i += 2)
    s += String.fromCharCode(bytes[i]! | (bytes[i + 1]! << 8));
  return s;
}
