import {spawnSync} from 'node:child_process';
import {readdir, readFile, mkdtemp, rm, writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const dir = await mkdtemp(join(tmpdir(), 'vn-lua51-'));
try {
  const exported = [
    'malloc',
    'free',
    'lua51_new',
    'lua51_close',
    'lua51_bind',
    'lua51_eval',
    'lua51_call',
    'lua51_compile',
    'lua51_top',
    'lua51_settop',
    'lua51_type',
    'lua51_number',
    'lua51_boolean',
    'lua51_string',
    'lua51_length',
    'lua51_pointer',
    'lua51_nil',
    'lua51_pushnumber',
    'lua51_pushboolean',
    'lua51_pushstring',
    'lua51_table',
    'lua51_rawset',
    'lua51_next',
    'lua51_global',
    'lua51_setglobal',
    'lua51_ref',
    'lua51_unref',
    'lua51_pushref',
    'lua51_fieldref',
    'lua51_invokeref',
    'lua51_newthreadref',
    'lua51_resumethread',
  ];
  const unused = new Set(['liolib.c', 'loslib.c', 'loadlib.c', 'ldblib.c', 'linit.c']);
  const sources = (await readdir(join(root, 'wasm/lua51/vendor')))
    .filter((n) => n.endsWith('.c') && !unused.has(n))
    .sort()
    .map((n) => `wasm/lua51/vendor/${n}`);
  const output = join(dir, 'lua51.wasm');
  const result = spawnSync(
    process.env.EMCC || 'emcc',
    [
      ...sources,
      'wasm/lua51/bridge.c',
      'wasm/lua51/pluto.c',
      '-Iwasm/lua51/vendor',
      '-O2',
      '--no-entry',
      '-sSTANDALONE_WASM=1',
      '-sSUPPORT_LONGJMP=wasm',
      '-mexception-handling',
      '-sALLOW_MEMORY_GROWTH=1',
      '-sINITIAL_MEMORY=16777216',
      // The native allocator (0x1401a1d70; Rev.3139 0x1401a0710) is plain realloc/free, and
      // game Lua stops the collector until collectgarbage("count") reaches its own threshold.
      '-sMAXIMUM_MEMORY=2147483648',
      '-sSTACK_SIZE=1048576',
      '-sFILESYSTEM=0',
      '-sERROR_ON_UNDEFINED_SYMBOLS=0',
      `-sEXPORTED_FUNCTIONS=${JSON.stringify(exported.map((n) => `_${n}`))}`,
      '-o',
      output,
    ],
    {cwd: root, stdio: 'inherit'},
  );
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`Lua WebAssembly build exited ${result.status}`);
  const bytes = await readFile(output);
  await writeFile(
    join(root, 'src/core/lua51/wasm-binary.ts'),
    '// Generated by npm run build:lua51 from wasm/lua51. Do not edit.\n// prettier-ignore\n' +
      `export const LUA51_WASM_BINARY = '${bytes.toString('base64')}';\n`,
  );
} finally {
  await rm(dir, {recursive: true, force: true});
}
