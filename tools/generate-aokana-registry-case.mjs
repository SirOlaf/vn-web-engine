/** Usage: node tools/generate-aokana-registry-case.mjs /path/to/UnicodeData-15.1.0.txt */
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

const path = process.argv[2];
if (!path) throw new Error('Supply the official Unicode 15.1.0 UnicodeData.txt file');
const bytes = await readFile(path);
const digest = createHash('sha256').update(bytes).digest('hex');
if (digest !== '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86')
  throw new Error('UnicodeData.txt is not the verified Unicode 15.1.0 data');
let pairs = '';
for (const line of bytes.toString('utf8').split('\n')) {
  if (!line) continue;
  const fields = line.split(';');
  if (fields.length !== 15) throw new Error('Invalid UnicodeData.txt record');
  const source = Number.parseInt(fields[0], 16);
  if (source > 0xffff || fields[12] === '') continue;
  const upper = Number.parseInt(fields[12], 16);
  if (upper > 0xffff) throw new Error('BMP simple uppercase mapping escapes UTF-16 unit range');
  pairs += source.toString(16).padStart(4, '0') + upper.toString(16).padStart(4, '0');
}
const source =
  `/** Unicode 15.1.0 BMP Simple_Uppercase_Mapping, field 12 of UnicodeData.txt.
 * Generated by tools/generate-aokana-registry-case.mjs; no game data.
 * Copyright 1991-2026 Unicode, Inc. Unicode License V3.
 * See third_party/unicode-15.1-registry/README.md and LICENSE.txt.
 */
export const AOKANA_REGISTRY_UPPERCASE_PAIRS =\n` +
  (pairs.match(/.{1,104}/g) ?? []).map((line) => `  '${line}'`).join(' +\n') +
  ';\n';
await writeFile(
  new URL('../src/engines/buriko/games/aokana/native/registry-case-data.ts', import.meta.url),
  source,
);
console.log(`Generated ${pairs.length / 8} BMP uppercase mappings`);
