function seeded(seed, length) {
  const bytes = new Uint8Array(length);
  let s = seed >>> 0;
  for (let i = 0; i < length; i++) {
    s ^= s << 13;
    s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5;
    s >>>= 0;
    bytes[i] = s & 255;
  }
  return bytes;
}
function fixtures() {
  return [
    [28, null],
    [87, 'b8g8r8a8'],
    [61, 'r8'],
    [49, 'r8g8'],
    [65, 'a8'],
    [71, 'bc1'],
    [74, 'bc2'],
    [77, 'bc3'],
    [98, 'bc7'],
  ].map(([format, decode], index) => {
    const block = decode?.startsWith('bc'),
      width = block ? 64 : 3,
      height = block ? 32 : 5;
    const mips = 1 + Math.floor(Math.log2(Math.max(width, height))),
      levels = [];
    for (let mip = 0; mip < mips; mip++) {
      const w = Math.max(1, width >> mip),
        h = Math.max(1, height >> mip);
      const length = decode ? gpuTextureByteLength(decode, w, h) : w * h * 4,
        bytes = seeded(0x1234567 + index * 0x1111111 + mip, length);
      if (decode === 'bc7')
        for (let k = 0; k < bytes.length / 16; k++) {
          const mode = k % 9;
          bytes[k * 16] =
            mode === 8 ? 0 : (bytes[k * 16] & ~((1 << (mode + 1)) - 1) & 255) | (1 << mode);
        }
      const rowBytes = block ? Math.ceil(w / 4) * (format === 71 ? 8 : 16) : length / h,
        rows = block ? Math.ceil(h / 4) : h;
      const pitch = rowBytes + 3,
        padded = new Uint8Array(pitch * rows).fill(0xcc);
      for (let y = 0; y < rows; y++)
        padded.set(bytes.subarray(y * rowBytes, (y + 1) * rowBytes), y * pitch);
      const expected = decode ? decodeGpuTexture(decode, w, h, bytes) : bytes;
      levels.push({
        width: w,
        height: h,
        bytes: [...bytes],
        initial: [...padded],
        pitch,
        expected: [...expected],
      });
    }
    return {format, width, height, mips, levels, block};
  });
}

