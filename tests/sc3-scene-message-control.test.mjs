import {test} from 'node:test';
import assert from 'node:assert/strict';
import {runtime, literal} from './sc3-fixtures.mjs';

test('01/08 all-slot phases preserve the native extra scheduling pass', async () => {
  let vm = runtime([1, 8, 0, 0, 3]);
  await vm.boot();
  let s = vm.state;
  s.put(0x5b10d8, 1);
  s.setFlag(0x9c6, 0);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(vm.pc(0), 19);
  assert.equal(s.get(0x179ccf8), 1);
  assert.equal(s.get(0x5b10d8), 0);
  assert.equal(s.flag(0x9c6), 1);
  vm = runtime([1, 8, 3, 0, 3]);
  await vm.boot();
  s = vm.state;
  s.put(0x179ccf8, 2);
  s.put(0x5b10b0, 2);
  s.put(0x5b10b4, 4, 1);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(vm.pc(0), 16);
  assert.equal(s.get(0x179ccf8), 3);
  vm = runtime([1, 8, 4, 0, 3]);
  await vm.boot();
  s = vm.state;
  s.put(0x179ccf8, 3);
  s.put(0x5b10b0, 0);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(vm.pc(0), 16);
  assert.equal(s.get(0x179ccf8), 0);
});

test('01/08 selected phases retain expression, opacity wait, audio and completion branches', async () => {
  let vm = runtime([1, 8, 10, ...literal(2), 0, 3]);
  await vm.boot();
  let s = vm.state;
  s.put(0x5d43e0, 1);
  s.setFlag(0x9c8, 0);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(vm.context(0).getUint32(0x13c, true), 2);
  assert.equal(s.get(0x179cd00), 1);
  assert.equal(s.flag(0x9c8), 1);
  vm = runtime([1, 8, 11, 0, 3]);
  await vm.boot();
  s = vm.state;
  vm.context(0).setUint32(0x13c, 1, true);
  s.put(0x179ccfc, 1);
  s.setVariable(0x83a, 255);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(vm.pc(0), 16);
  s.setVariable(0x83a, 256);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(vm.pc(0), 21);
  vm = runtime([1, 8, 12, 0, 3]);
  await vm.boot();
  s = vm.state;
  vm.context(0).setUint32(0x13c, 0, true);
  s.put(0x179ccf8, 1);
  s.put(0x179cae8, 7);
  s.put(0x17ac258, 0);
  s.put(0x5a70d8 + 3 * 4, 0);
  s.put(0x5a7110 + 3 * 0x98 + 0x40, 99);
  s.put(0x5a7110 + 3 * 0x98 + 0x48, 100, 8);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(s.get(0x179ccf8), 2);
  assert.equal(s.get(0x5a70d8 + 3 * 4), 1);
  assert.equal(s.get(0x5a7110 + 3 * 0x98 + 0x40), 0);
  assert.equal(s.view(0x5a7110 + 3 * 0x98 + 0x48, 8).getBigUint64(0, true), 0n);
  vm = runtime([1, 8, 13, 0, 3, 1, 8, 14, 0, 3]);
  await vm.boot();
  s = vm.state;
  s.put(0x179ccf8, 2);
  s.put(0x5b10b0, 2);
  s.put(0x5b10b4, 4, 1);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(s.get(0x179ccf8), 3);
  s.put(0x5b10b0, 0);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(s.get(0x179ccf8), 0);
  assert.equal(vm.pc(0), 26);
});

test('01/08 inert selectors consume only the selector and phase 20 waits on active text', async () => {
  for (const selector of [5, 6, 7, 8, 9, 15, 16, 17, 18, 19, 21, 255]) {
    const vm = runtime([1, 8, selector, 0, 3]);
    await vm.boot();
    assert.equal(vm.runContext(0), 'yield');
    assert.equal(vm.pc(0), 21);
  }
  const vm = runtime([1, 8, 20, 0, 3]);
  await vm.boot();
  vm.state.put(0x179ccf8, 1);
  vm.state.put(0x5b10b0, 1);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(vm.pc(0), 16);
  vm.state.put(0x5b10b0, 2);
  assert.equal(vm.runContext(0), 'yield');
  assert.equal(vm.pc(0), 21);
});
